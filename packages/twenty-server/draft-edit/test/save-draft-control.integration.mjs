import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { createSaveDraftControl } from '../src/save-draft-control.mjs';
const require = createRequire('/app/package.json');
const React = require('react');
const { createRoot } = require('react-dom/client');
const { JSDOM } = require('jsdom');
const dom = new JSDOM('<!doctype html><html><body><div id="root"></div></body></html>', { url: 'http://localhost/' });
globalThis.window = dom.window; globalThis.document = dom.window.document; globalThis.IS_REACT_ACT_ENVIRONMENT = true;
const root = createRoot(document.getElementById('root'));
const Control = createSaveDraftControl(React);
const target = { accountId: 'account', folder: 'Drafts', uidValidity: '2', uid: 3 };
const calls = [];
const callTool = async (name, args) => {
  calls.push([name, args]);
  if (name === 'list_email_drafts') return { success: true, result: { drafts: [{ headerMessageId: '<fixture@example.invalid>', target }], truncated: false } };
  if (name === 'inspect_email_draft') return { success: true, result: { revision: 'a'.repeat(64), subject: 'Funding', text: 'Before' } };
  if (name === 'update_email_draft') return { success: true, result: { status: 'updated', target: { ...target, uid: 4 } } };
  throw new Error('Unexpected tool');
};
let saved;
const props = { accountId: 'account', messageId: '<fixture@example.invalid>', initialSubject: 'Funding', initialText: 'Before', callTool, getChanges: () => ({ body: { text: 'After' } }), onSaved: (result) => { saved = result; }, makeOperationId: () => 'operation-123456789' };
await React.act(async () => { root.render(React.createElement(Control, props)); });
assert.equal(document.querySelector('button').disabled, false);
await React.act(async () => { document.querySelector('button').click(); });
assert.equal(document.querySelector('[role=status]').textContent, 'Draft saved');
assert.equal(saved.target.uid, 4);
assert.equal(calls.filter(([name]) => name === 'update_email_draft').length, 1);
assert.deepEqual(calls.at(-1)[1].changes, { body: { text: 'After' } });
await React.act(async () => { root.render(React.createElement(Control, { ...props, messageId: '<missing@example.invalid>' })); });
assert.equal(document.querySelector('button').disabled, true);
assert.match(document.querySelector('[role=alert]').textContent, /ambiguous/);
let release;
const pending = new Promise((resolve) => { release = resolve; });
const slowCalls = [];
const slowTool = async (name, args) => {
  slowCalls.push(name);
  if (name === 'update_email_draft') return pending;
  return callTool(name, args);
};
await React.act(async () => { root.render(React.createElement(Control, { ...props, callTool: slowTool, getChanges: () => ({ files: [{ id: 'file', name: 'new.pdf' }] }) })); });
await React.act(async () => { document.querySelector('button').click(); document.querySelector('button').click(); });
assert.equal(slowCalls.filter((name) => name === 'update_email_draft').length, 1);
await React.act(async () => { release({ success: false, result: { status: 'recovery_required' } }); });
assert.equal(document.querySelector('button').disabled, true);
assert.match(document.querySelector('[role=alert]').textContent, /Do not retry/);
assert.equal(slowCalls.includes('send_email'), false);
await React.act(async () => { root.unmount(); });
dom.window.close();
console.log('PASS: Save draft control inspects identity, saves once and rejects an ambiguous selection');
